-- =====================================================================
--  Buchhaltung: Monat für den Steuerberater (BMD, RZL)
-- =====================================================================
--
-- Die Kanzlei bekommt je Monat Buchungen, Personenkonten und alle Belege als
-- ZIP. Was übergeben ist, steht in fibu_uebergaben und kommt beim nächsten
-- Monat nicht noch einmal. Kontonummern stimmt der Betrieb mit der Kanzlei ab
-- (firma.fibu_konten); die Vorbelegung ist nur ein Vorschlag.
--
-- Lieferanten sind freier Text, die Kanzlei braucht aber Kreditorennummern:
-- kreditor_konten vergibt sie einmal und merkt sie sich.
--
-- Eine übergebene Eingangsrechnung ändert sich nicht mehr still — erst die
-- Übergabe zurücknehmen. Rechnungen sind ohnehin festgeschrieben.
--
-- Nur der Chef.
-- =====================================================================

alter table public.firma
  add column fibu_format text not null default 'bmd' check (fibu_format in ('bmd', 'rzl')),
  add column fibu_konten jsonb not null default '{
    "erloes20": 4000, "erloes13": 4005, "erloes10": 4010, "erloes0": 4050, "erloesBau": 4060,
    "material": 5000, "fremdleistung": 5800, "werkzeug": 5100, "fahrzeug": 7320, "buero": 7600, "sonstiges": 7800
  }'::jsonb;

-- Bauleistung vom Subunternehmer (§ 19 Abs. 1a UStG): netto = brutto, Steuer rechnet die Kanzlei
alter table public.eingangsrechnungen
  add column reverse_charge boolean not null default false;

create table public.kreditor_konten (
  schluessel text primary key,
  name text not null,
  konto int generated by default as identity (start with 30001) unique,
  created_at timestamptz not null default now()
);

create table public.fibu_uebergaben (
  id uuid primary key default gen_random_uuid(),
  von date not null,
  bis date not null,
  format text not null check (format in ('bmd', 'rzl')),
  erstellt_von uuid default auth.uid() references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.fibu_uebergabe_belege (
  uebergabe_id uuid not null references public.fibu_uebergaben(id) on delete cascade,
  beleg_id uuid unique references public.belege(id) on delete restrict,
  eingang_id uuid unique references public.eingangsrechnungen(id) on delete restrict,
  check (num_nonnulls(beleg_id, eingang_id) = 1)
);
create index on public.fibu_uebergabe_belege (uebergabe_id);

alter table public.kreditor_konten enable row level security;
alter table public.fibu_uebergaben enable row level security;
alter table public.fibu_uebergabe_belege enable row level security;
create policy kreditor_konten_chef on public.kreditor_konten for all to authenticated
  using (public.ist_chef()) with check (public.ist_chef());
create policy fibu_uebergaben_chef on public.fibu_uebergaben for all to authenticated
  using (public.ist_chef()) with check (public.ist_chef());
create policy fibu_uebergabe_belege_chef on public.fibu_uebergabe_belege for all to authenticated
  using (public.ist_chef()) with check (public.ist_chef());

-- Fehlende Kreditoren anlegen, Nummern zurück
create function public.kreditor_konten_holen(p_namen text[])
returns table (schluessel text, konto int)
language plpgsql set search_path = public as $$
begin
  if not public.ist_chef() then
    raise exception 'Nur der Chef.';
  end if;
  insert into public.kreditor_konten (schluessel, name)
  select distinct on (lower(btrim(n))) lower(btrim(n)), btrim(n)
    from unnest(p_namen) n
   where btrim(n) <> ''
   order by lower(btrim(n)), n
  on conflict (schluessel) do nothing;
  return query
    select k.schluessel, k.konto from public.kreditor_konten k
     where k.schluessel in (select lower(btrim(n)) from unnest(p_namen) n);
end $$;

-- Alles oder nichts: entweder ist der ganze Monat übergeben oder gar nichts
create function public.fibu_uebergeben(p_von date, p_bis date, p_format text, p_belege uuid[], p_eingaenge uuid[])
returns uuid
language plpgsql set search_path = public as $$
declare
  v_id uuid;
begin
  if not public.ist_chef() then
    raise exception 'Nur der Chef.';
  end if;
  if coalesce(cardinality(p_belege), 0) + coalesce(cardinality(p_eingaenge), 0) = 0 then
    raise exception 'In diesem Zeitraum gibt es nichts zu übergeben.';
  end if;
  insert into public.fibu_uebergaben (von, bis, format) values (p_von, p_bis, p_format) returning id into v_id;
  insert into public.fibu_uebergabe_belege (uebergabe_id, beleg_id) select v_id, unnest(coalesce(p_belege, '{}'));
  insert into public.fibu_uebergabe_belege (uebergabe_id, eingang_id) select v_id, unnest(coalesce(p_eingaenge, '{}'));
  return v_id;
end $$;

-- Übergeben = was die Kanzlei hat, darf sich nicht still ändern
create function public.eingang_uebergeben_schutz() returns trigger
language plpgsql set search_path = public as $$
begin
  if not exists (select 1 from public.fibu_uebergabe_belege where eingang_id = old.id) then
    return coalesce(new, old);
  end if;
  if tg_op = 'DELETE'
     or (new.lieferant, new.nummer, new.datum, new.netto, new.ust_satz, new.ust, new.brutto, new.kategorie, new.reverse_charge)
        is distinct from (old.lieferant, old.nummer, old.datum, old.netto, old.ust_satz, old.ust, old.brutto, old.kategorie, old.reverse_charge) then
    raise exception 'Schon an die Buchhaltung übergeben. Bitte zuerst die Übergabe zurücknehmen.';
  end if;
  return new;
end $$;
create trigger eingang_uebergeben_schutz before update or delete on public.eingangsrechnungen
  for each row execute function public.eingang_uebergeben_schutz();
