-- Fertige Rechnungen sind festgeschrieben: nur noch Zahlungsstatus und Storno.
create or replace function public.beleg_schutz() returns trigger
language plpgsql as $$
begin
  if old.typ = 'rechnung' and old.status <> 'entwurf' then
    if new.status = 'entwurf' then
      raise exception 'Eine fertige Rechnung kann nicht zurück in den Entwurf.';
    end if;
    if (new.typ, new.nummer, new.datum, new.netto, new.ust, new.brutto, new.ust_satz, new.reverse_charge,
        new.empf_name, new.empf_zusatz, new.empf_strasse, new.empf_plz, new.empf_ort, new.empf_uid,
        new.leistung_von, new.leistung_bis)
