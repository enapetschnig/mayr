-- Bestand je Artikel und Lagerort
create view public.lagerbestand with (security_invoker = true) as
select artikel_id, lagerort_id,
       sum(case art when 'abgang' then -menge when 'ausfassung' then -menge
                    when 'direkt' then 0 else menge end) as bestand
from public.material_buchungen
where artikel_id is not null and lagerort_id is not null
group by artikel_id, lagerort_id;

-- Material je Projekt: ausgefasst, zurück, direkt, verbraucht, noch offen.
-- Material aus Regieberichten zählt beim Regiebericht, nicht hier.
create view public.projekt_material with (security_invoker = true) as
select b.projekt_id,
       b.artikel_id,
       coalesce(a.bezeichnung, b.bezeichnung) as bezeichnung,
       coalesce(a.einheit, b.einheit, 'Stk') as einheit,
       coalesce(sum(b.menge) filter (where b.art = 'ausfassung'), 0) as ausgefasst,
       coalesce(sum(b.menge) filter (where b.art = 'rueckgabe'), 0) as zurueck,
       coalesce(sum(b.menge) filter (where b.art = 'direkt'), 0) as direkt,
       sum(case b.art when 'rueckgabe' then -b.menge else b.menge end) as verbraucht,
       coalesce(sum(case b.art when 'rueckgabe' then -b.menge else b.menge end)
                filter (where b.rechnung_id is null), 0) as offen,
       max(b.created_at) as zuletzt
from public.material_buchungen b
left join public.artikel a on a.id = b.artikel_id
where b.projekt_id is not null
  and b.regiebericht_id is null
  and b.art in ('ausfassung','rueckgabe','direkt')
group by b.projekt_id, b.artikel_id, coalesce(a.bezeichnung, b.bezeichnung), coalesce(a.einheit, b.einheit, 'Stk');

-- Kennzahlen je Projekt für Listen und die Chef-Übersicht
create view public.projekt_zahlen with (security_invoker = true) as
select p.id as projekt_id,
       coalesce((select sum(z.stunden) from public.zeiten z where z.projekt_id = p.id), 0) as stunden,
       coalesce((select sum(z.stunden) from public.zeiten z
                 where z.projekt_id = p.id and z.rechnung_id is null), 0) as stunden_offen,
       (select count(*) from public.regieberichte r
         where r.projekt_id = p.id and r.status = 'entwurf') as regie_entwurf,
       (select count(*) from public.regieberichte r
         where r.projekt_id = p.id and r.status = 'unterschrieben' and r.rechnung_id is null) as regie_offen,
       coalesce((select sum(case m.art when 'rueckgabe' then -m.menge else m.menge end * coalesce(m.ek_preis, 0))
                 from public.material_buchungen m
                 where m.projekt_id = p.id and m.rechnung_id is null
                   and m.art in ('ausfassung','rueckgabe','direkt')), 0) as material_offen_ek
from public.projekte p;

