-- ── Materialbuchungen: Lager und Projekt in einer Tabelle ───────────────
--   zugang      Lager +            (Wareneingang)
--   abgang      Lager −            (Schwund, Umlagerung)
--   korrektur   Lager ±            (Inventur; menge mit Vorzeichen)
--   ausfassung  Lager −, Projekt + (mitgenommen)
--   rueckgabe   Lager +, Projekt − (zurückgebracht)
--   direkt               Projekt + (direkt gekauft/geliefert, ohne Lager)
-- Freie Positionen ohne Artikel tragen bezeichnung + einheit.
create table public.material_buchungen (
  id uuid primary key default gen_random_uuid(),
  art text not null check (art in ('zugang','abgang','korrektur','ausfassung','rueckgabe','direkt')),
  artikel_id uuid references public.artikel(id) on delete restrict,
  bezeichnung text,
  einheit text,
  menge numeric(12,3) not null,
  lagerort_id uuid references public.lagerorte(id) on delete restrict,
  projekt_id uuid references public.projekte(id) on delete cascade,
  regiebericht_id uuid references public.regieberichte(id) on delete set null,
  ek_preis numeric(12,4),
  -- ein Scan-Durchgang = ein Vorgang (wie ein Lieferschein)
  vorgang uuid,
  notiz text,
  rechnung_id uuid references public.belege(id) on delete set null,
  user_id uuid default auth.uid() references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint artikel_oder_text check (artikel_id is not null or coalesce(btrim(bezeichnung), '') <> ''),
  constraint buchung_passt check (case art
    when 'korrektur' then menge <> 0 and artikel_id is not null and lagerort_id is not null
    when 'zugang' then menge > 0 and artikel_id is not null and lagerort_id is not null
    when 'abgang' then menge > 0 and artikel_id is not null and lagerort_id is not null
    when 'ausfassung' then menge > 0 and projekt_id is not null and (artikel_id is null or lagerort_id is not null)
    when 'rueckgabe' then menge > 0 and projekt_id is not null and (artikel_id is null or lagerort_id is not null)
    when 'direkt' then menge > 0 and projekt_id is not null and lagerort_id is null
  end)
);
create index on public.material_buchungen (projekt_id);
create index on public.material_buchungen (artikel_id, lagerort_id);
create index on public.material_buchungen (regiebericht_id);
create index on public.material_buchungen (vorgang);

