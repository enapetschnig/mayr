       (old.typ, old.nummer, old.datum, old.netto, old.ust, old.brutto, old.ust_satz, old.reverse_charge,
        old.empf_name, old.empf_zusatz, old.empf_strasse, old.empf_plz, old.empf_ort, old.empf_uid,
        old.leistung_von, old.leistung_bis) then
      raise exception 'Eine fertige Rechnung ist festgeschrieben. Bitte stornieren und neu erstellen.';
    end if;
  end if;
  return new;
end $$;
