-- Fertigstellen: Summen aus den Positionen, nächste Nummer, Fälligkeit bzw.
-- Gültigkeit. Danach ist eine Rechnung festgeschrieben.
create or replace function public.beleg_fertigstellen(p_id uuid) returns text
language plpgsql security definer set search_path = public as $$
declare
  b public.belege;
  f public.firma;
  v_netto numeric(12,2);
  v_ust numeric(12,2);
  v_nr text;
begin
  if not public.ist_chef() then
    raise exception 'Nur der Chef kann Belege fertigstellen.';
  end if;
  select * into b from public.belege where id = p_id for update;
  if b.id is null then
    raise exception 'Beleg nicht gefunden.';
  end if;
  if b.status <> 'entwurf' then
    return b.nummer;
  end if;
  if not exists (select 1 from public.beleg_positionen where beleg_id = p_id and art not in ('titel','text')) then
    raise exception 'Der Beleg hat noch keine Position mit Betrag.';
  end if;
  if coalesce(btrim(b.empf_name), '') = '' then
    raise exception 'Bitte zuerst den Empfänger eintragen.';
  end if;

  select * into f from public.firma where id = 1;
  select coalesce(sum(gesamt), 0) into v_netto from public.beleg_positionen where beleg_id = p_id;
  v_ust := case when b.reverse_charge or f.kleinunternehmer then 0 else round(v_netto * b.ust_satz / 100, 2) end;
  v_nr := public.naechste_nummer(b.typ, b.datum);

  update public.belege set
    nummer = v_nr,
    status = 'offen',
    fertig_am = now(),
    netto = v_netto,
    ust = v_ust,
    brutto = v_netto + v_ust,
    faellig_am = case when b.typ = 'rechnung' then coalesce(b.faellig_am, b.datum + f.zahlungsziel_tage) end,
    gueltig_bis = case when b.typ = 'angebot' then coalesce(b.gueltig_bis, b.datum + f.angebot_gueltig_tage) end
  where id = p_id;
  return v_nr;
end $$;

-- Storno: Rechnung bleibt (lückenlose Nummern), Stunden/Material/
-- Regieberichte sind wieder frei für eine neue Rechnung.
create or replace function public.beleg_stornieren(p_id uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.ist_chef() then
    raise exception 'Nur der Chef kann stornieren.';
  end if;
  update public.belege set status = 'storniert'
   where id = p_id and typ = 'rechnung' and status in ('offen','bezahlt');
  if not found then
    raise exception 'Nur fertige Rechnungen können storniert werden.';
  end if;
  update public.zeiten set rechnung_id = null where rechnung_id = p_id;
  update public.material_buchungen set rechnung_id = null where rechnung_id = p_id;
  update public.regieberichte set rechnung_id = null where rechnung_id = p_id;
end $$;

-- Artikelsuche: alle Wörter müssen vorkommen („nym 3x1,5“ findet
-- „NYM-J 3x1,5 mm² Ring 100 m“); Tippfehler fängt die Ähnlichkeit ab.
create or replace function public.artikel_suchen(p_q text, p_anzahl int default 30)
returns setof public.artikel
language sql stable set search_path = public, extensions as $$
  with w as (
    select btrim(coalesce(p_q, '')) as q,
           array_remove(regexp_split_to_array(lower(btrim(coalesce(p_q, ''))), '\s+'), '') as woerter
  )
  select a.*
  from public.artikel a, w
  where a.aktiv
    and (
      a.ean = w.q
      or a.artikelnummer = w.q
      or lower(a.hersteller_nr) = lower(w.q)
      or not exists (
        select 1 from unnest(w.woerter) x
        where lower(a.bezeichnung || ' ' || coalesce(a.hersteller, '') || ' ' || coalesce(a.hersteller_nr, '')
                    || ' ' || coalesce(a.artikelnummer, '') || ' ' || coalesce(a.kategorie, ''))
              not like '%' || x || '%'
      )
      or (length(w.q) >= 4 and word_similarity(lower(w.q), lower(a.bezeichnung)) > 0.5)
    )
  order by (a.ean = w.q) desc, a.lagerartikel desc,
           word_similarity(lower(w.q), lower(a.bezeichnung)) desc, a.bezeichnung
  limit greatest(1, least(p_anzahl, 200))
$$;

-- Strichcode → Artikel (EAN am Artikel oder zugeordneter Zusatzcode)
create or replace function public.artikel_zu_code(p_code text)
returns table (artikel_id uuid, menge numeric)
language sql stable set search_path = public as $$
  select c.artikel_id, c.menge from public.artikel_codes c where c.code = btrim(p_code)
  union all
  select a.id, 1::numeric from public.artikel a where a.ean = btrim(p_code) and a.aktiv
  limit 1
$$;

