-- Ein unterschriebener Regiebericht ist ein Beleg für den Kunden: Inhalt fest,
-- nur die Verrechnung (rechnung_id) darf sich noch ändern.
create or replace function public.regie_schutz() returns trigger
language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'entwurf' then
      raise exception 'Ein unterschriebener Regiebericht kann nicht gelöscht werden.';
    end if;
    return old;
  end if;
  if old.status = 'unterschrieben'
     and (to_jsonb(new) - 'rechnung_id' - 'updated_at') is distinct from (to_jsonb(old) - 'rechnung_id' - 'updated_at') then
    raise exception 'Ein unterschriebener Regiebericht ist festgeschrieben.';
  end if;
  return new;
end $$;
create trigger regieberichte_schutz before update or delete on public.regieberichte
  for each row execute function public.regie_schutz();

-- Verrechnete oder unterschriebene Stunden und Materialbuchungen sind fest.
create or replace function public.regie_unterschrieben(p_id uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select p_id is not null and exists (
    select 1 from public.regieberichte where id = p_id and status = 'unterschrieben')
$$;

create or replace function public.buchung_schutz() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  -- In einen unterschriebenen Regiebericht kommt nichts mehr dazu.
  if tg_op in ('INSERT','UPDATE')
     and new.regiebericht_id is not null
     and (tg_op = 'INSERT' or new.regiebericht_id is distinct from old.regiebericht_id)
     and public.regie_unterschrieben(new.regiebericht_id) then
    raise exception 'Der Regiebericht ist schon unterschrieben.';
  end if;
  if tg_op = 'INSERT' then
    return new;
  end if;
  if old.rechnung_id is null and not public.regie_unterschrieben(old.regiebericht_id) then
    return coalesce(new, old);
  end if;
  if tg_op = 'DELETE' then
    raise exception 'Schon verrechnet oder im unterschriebenen Regiebericht — kann nicht mehr gelöscht werden.';
  end if;
  if (to_jsonb(new) - 'rechnung_id') is distinct from (to_jsonb(old) - 'rechnung_id') then
    raise exception 'Schon verrechnet oder im unterschriebenen Regiebericht — kann nicht mehr geändert werden.';
  end if;
  return new;
end $$;
revoke execute on function public.regie_unterschrieben(uuid) from public, anon;
