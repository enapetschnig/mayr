-- =====================================================================
--  Anlagen & Wartung / E-Check
-- =====================================================================
--
-- Anlage = etwas beim Kunden, das regelmäßig geprüft wird (Verteiler,
-- Elektroanlage für den E-Check, Blitzschutz, Notlicht, PV …), mit
-- Prüfintervall in Monaten. Der QR-Aufkleber trägt die Adresse
-- /anlagen/<id> — Handykamera oder Scanner in der App öffnen die Anlage.
--
-- Prüfung = Prüfprotokoll am Handy: Besichtigung (Liste mit OK/Mangel),
-- Messungen je Stromkreis (Isolationswiderstand, Schleifenimpedanz,
-- FI-Auslösestrom/-zeit), Ergebnis, Mängel, Kundenunterschrift. Wie beim
-- Regiebericht: unterschrieben = festgeschrieben (nur `rechnung_id` darf
-- sich noch ändern), Zeitpunkt setzt der Server. Mit der Unterschrift
-- springt die nächste Prüfung der Anlage weiter (Datum + Intervall).
-- Verrechnet wird an der Quelle: `pruefungen.rechnung_id`, Position mit
-- quelle {"pruefung": [id]}.
-- =====================================================================

create table public.anlagen (
  id uuid primary key default gen_random_uuid(),
  nummer int generated by default as identity (start with 1) unique,
  kunde_id uuid references public.kunden(id) on delete set null,
  projekt_id uuid references public.projekte(id) on delete set null,
  bezeichnung text not null,
  art text not null default 'elektroanlage'
    check (art in ('elektroanlage','verteiler','blitzschutz','notlicht','pv','ladestation','geraet','sonstige')),
  standort text,
  strasse text,
  plz text,
  ort text,
  hersteller text,
  typ text,
  baujahr int check (baujahr between 1900 and 2100),
  -- leer = keine wiederkehrende Prüfung
  intervall_monate int check (intervall_monate between 1 and 120),
  letzte_pruefung date,
  naechste_pruefung date,
  -- vereinbarter Preis netto je Prüfung (Wartungsvertrag) — kommt auf die Rechnung
  preis numeric(10,2) check (preis >= 0),
  notiz text,
  aktiv boolean not null default true,
  erstellt_von uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index on public.anlagen (kunde_id);
create index on public.anlagen (naechste_pruefung) where aktiv;
create trigger anlagen_updated before update on public.anlagen
  for each row execute function public.updated_at_setzen();

-- Nummernkreis PR-2026-001 für Prüfprotokolle
alter table public.nummernkreise drop constraint nummernkreise_typ_check;
alter table public.nummernkreise add constraint nummernkreise_typ_check
  check (typ in ('projekt','angebot','rechnung','regie','pruefung'));

create or replace function public.naechste_nummer(p_typ text, p_datum date) returns text
language plpgsql security definer set search_path = public as $$
declare
  v_jahr int := extract(year from coalesce(p_datum, current_date))::int;
  v_n int;
begin
  insert into public.nummernkreise as nk (typ, jahr, letzte)
  values (p_typ, v_jahr, 1)
  on conflict (typ, jahr) do update set letzte = nk.letzte + 1
  returning nk.letzte into v_n;

  return case p_typ
    when 'projekt' then v_jahr || '-' || lpad(v_n::text, 4, '0')
    when 'angebot' then 'AN-' || v_jahr || '-' || lpad(v_n::text, 3, '0')
    when 'rechnung' then 'RE-' || v_jahr || '-' || lpad(v_n::text, 3, '0')
    when 'regie' then 'RB-' || v_jahr || '-' || lpad(v_n::text, 3, '0')
    when 'pruefung' then 'PR-' || v_jahr || '-' || lpad(v_n::text, 3, '0')
  end;
end $$;
revoke execute on function public.naechste_nummer(text, date) from public, anon, authenticated;

create table public.pruefungen (
  id uuid primary key default gen_random_uuid(),
  nummer text unique,
  anlage_id uuid not null references public.anlagen(id) on delete restrict,
  datum date not null default current_date,
  art text not null default 'wiederkehrend' check (art in ('erst','wiederkehrend','e-check','nach_reparatur')),
  netz text,
  messgeraet text,
  -- [{"punkt": "…", "ok": true|false|null}]
  besichtigung jsonb not null default '[]'::jsonb,
  -- [{"stromkreis": "…", "schutz": "B16", "querschnitt": "3x1,5", "riso": 250, "zs": 0.8, "fi_in": 30, "fi_ia": 21, "fi_ta": 24}]
  messungen jsonb not null default '[]'::jsonb,
  erder_ohm numeric(10,2),
  ergebnis text check (ergebnis in ('ok','maengel','gefahr')),
  maengel text,
  bemerkung text,
  status text not null default 'entwurf' check (status in ('entwurf','unterschrieben')),
  unterschrift_pfad text,
  unterschrift_name text,
  unterschrieben_am timestamptz,
  rechnung_id uuid references public.belege(id) on delete set null,
  erstellt_von uuid default auth.uid() references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index on public.pruefungen (anlage_id);
create index on public.pruefungen (rechnung_id);
create trigger pruefungen_updated before update on public.pruefungen
  for each row execute function public.updated_at_setzen();

create function public.pruefung_nummer_vergeben() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.nummer := public.naechste_nummer('pruefung', new.datum);
  return new;
end $$;
create trigger pruefungen_nummer before insert on public.pruefungen
  for each row execute function public.pruefung_nummer_vergeben();

-- Unterschreiben: Bild, Name und Ergebnis Pflicht, Zeitpunkt vom Server.
-- Danach festgeschrieben; löschen nur Entwürfe.
create function public.pruefung_schutz() returns trigger
language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'entwurf' then
      raise exception 'Ein unterschriebenes Prüfprotokoll kann nicht gelöscht werden.';
    end if;
    return old;
  end if;
  if old.status = 'unterschrieben' then
    if (to_jsonb(new) - 'rechnung_id' - 'updated_at') is distinct from (to_jsonb(old) - 'rechnung_id' - 'updated_at') then
      raise exception 'Ein unterschriebenes Prüfprotokoll ist festgeschrieben.';
    end if;
    return new;
  end if;
  if new.rechnung_id is not null and new.status <> 'unterschrieben' then
    raise exception 'Verrechnen lässt sich nur ein unterschriebenes Prüfprotokoll.';
  end if;
  if new.status = 'unterschrieben' then
    if new.unterschrift_pfad is null or btrim(coalesce(new.unterschrift_name, '')) = '' then
      raise exception 'Zum Unterschreiben fehlen Unterschrift oder Name.';
    end if;
    if new.ergebnis is null then
      raise exception 'Bitte zuerst das Ergebnis der Prüfung wählen.';
    end if;
    if new.ergebnis <> 'ok' and btrim(coalesce(new.maengel, '')) = '' then
      raise exception 'Bei Mängeln bitte die Mängel beschreiben.';
    end if;
    new.unterschrieben_am := now();
  end if;
  return new;
end $$;
create trigger pruefungen_schutz before update or delete on public.pruefungen
  for each row execute function public.pruefung_schutz();

-- Unterschrieben → Anlage: letzte Prüfung, nächste = Datum + Intervall
create function public.pruefung_termin() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.anlagen a set
    letzte_pruefung = greatest(coalesce(a.letzte_pruefung, new.datum), new.datum),
    naechste_pruefung = case when a.intervall_monate is null then null
      else (greatest(coalesce(a.letzte_pruefung, new.datum), new.datum) + make_interval(months => a.intervall_monate))::date end
  where a.id = new.anlage_id;
  return new;
end $$;
create trigger pruefungen_termin after update of status on public.pruefungen
  for each row when (new.status = 'unterschrieben' and old.status = 'entwurf')
  execute function public.pruefung_termin();

-- Position gelöscht → Prüfung wieder frei (übrige Quellen wie bisher)
create or replace function public.position_freigeben() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if old.quelle is null then return old; end if;
  update public.zeiten set rechnung_id = null
   where rechnung_id = old.beleg_id
     and id in (select x::uuid from jsonb_array_elements_text(coalesce(old.quelle->'zeiten', '[]'::jsonb)) x);
  update public.material_buchungen set rechnung_id = null
   where rechnung_id = old.beleg_id
     and id in (select x::uuid from jsonb_array_elements_text(coalesce(old.quelle->'material', '[]'::jsonb)) x);
  update public.regieberichte set rechnung_id = null
   where rechnung_id = old.beleg_id
     and id in (select x::uuid from jsonb_array_elements_text(coalesce(old.quelle->'regie', '[]'::jsonb)) x);
  update public.belege set abgezogen_in = null
   where abgezogen_in = old.beleg_id
     and id in (select x::uuid from jsonb_array_elements_text(coalesce(old.quelle->'teil', '[]'::jsonb)) x);
  update public.pruefungen set rechnung_id = null
   where rechnung_id = old.beleg_id
     and id in (select x::uuid from jsonb_array_elements_text(coalesce(old.quelle->'pruefung', '[]'::jsonb)) x);
  return old;
end $$;

-- Rechnung storniert → Prüfungen wieder frei
create function public.pruefung_freigeben_bei_storno() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.pruefungen set rechnung_id = null where rechnung_id = new.id;
  return new;
end $$;
create trigger belege_pruefung_storno after update of status on public.belege
  for each row when (new.status = 'storniert' and old.status <> 'storniert')
  execute function public.pruefung_freigeben_bei_storno();

