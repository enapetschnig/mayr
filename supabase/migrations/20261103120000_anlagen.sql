  using (public.ist_aktiv()) with check (public.ist_aktiv());
create policy pruefungen_loeschen on public.pruefungen for delete to authenticated
  using (erstellt_von = auth.uid() or public.ist_chef());

-- Verrechnen (rechnung_id setzen oder lösen) darf nur der Chef
create function public.pruefung_verrechnen_pruefen() returns trigger
language plpgsql as $$
begin
  if auth.uid() is not null and new.rechnung_id is distinct from old.rechnung_id and not public.ist_chef() then
    raise exception 'Verrechnen kann nur der Chef.';
  end if;
  return new;
end $$;
create trigger pruefungen_verrechnen before update of rechnung_id on public.pruefungen
  for each row execute function public.pruefung_verrechnen_pruefen();

